import os
from pathlib import Path
import pytest
from typing import Dict, Optional


def load_tool_reports(reports_dir: str = "reports") -> Dict[str, str]:
    """Loads static analysis tool reports (pylint, bandit, radon) if available.

    Args:
        reports_dir: Path to directory containing tool reports.

    Returns:
        Dict mapping report filenames to their content strings.
    """
    reports_path = Path(reports_dir)
    if not reports_path.is_dir():
        reports_path = Path("notebooks/reports")
        if not reports_path.is_dir():
            return {}

    tool_reports: Dict[str, str] = {}
    known_reports = ["pylint_report.txt", "bandit_report.txt", "radon_report.txt", "bugsinpy_test_report.txt"]
    for fname in known_reports:
        fp = reports_path / fname
        if fp.is_file():
            try:
                with open(fp, "r", encoding="utf-8", errors="ignore") as f:
                    tool_reports[fname] = f.read()
            except Exception:
                pass
    return tool_reports


def format_tool_diagnostics_context(tool_reports: Dict[str, str], max_char_budget: int = 50_000) -> str:
    """Formats static analyzer outputs (Pylint, Bandit, Radon) into context blocks.

    Args:
        tool_reports: Mapping of report filenames to report contents.
        max_char_budget: Character limit for tool diagnostics block.

    Returns:
        Formatted markdown block of static tool diagnostics.
    """
    if not tool_reports:
        return "*[No pre-generated static tool report files found in reports directory]*"

    blocks = []
    total_chars = 0
    for fname, report in sorted(tool_reports.items()):
        header = f"#### Tool Diagnostic: `{fname}`\n```\n"
        footer = "\n```\n"
        available = max_char_budget - total_chars - len(header) - len(footer)
        if available <= 0:
            blocks.append("\n> *[Truncated remaining tool diagnostics]*\n")
            break

        snippet = report if len(report) <= available else report[:available] + "\n... [Truncated]"
        blocks.append(f"{header}{snippet}{footer}")
        total_chars += len(header) + len(snippet) + len(footer)

    return "\n".join(blocks)


def format_codebase_context(source_files: Dict[str, str], max_char_budget: int = 150_000) -> str:
    """Formats ingested source files into a structured markdown block for model context.

    Args:
        source_files: Dictionary mapping file paths to code contents.
        max_char_budget: Maximum character limit to keep context concise.

    Returns:
        Formatted markdown string representation of the codebase.
    """
    blocks = []
    total_chars = 0
    for path, code in sorted(source_files.items()):
        header = f"### File: `{path}`\n```\n"
        footer = "\n```\n"
        available = max_char_budget - total_chars - len(header) - len(footer)
        if available <= 0:
            blocks.append("\n> *[Truncated remaining files due to context budget]*\n")
            break

        snippet = code if len(code) <= available else code[:available] + "\n... [Content Truncated]"
        blocks.append(f"{header}{snippet}{footer}")
        total_chars += len(header) + len(snippet) + len(footer)

    return "\n".join(blocks)


def build_evaluation_prompt(
    source_code_dict: Dict[str, str],
    report_text: str,
    weights: Dict[str, float],
    tool_reports_dict: Optional[Dict[str, str]] = None,
) -> str:
    """Constructs the unified evaluation prompt shared identically across all LLM judges."""
    code_context = format_codebase_context(source_code_dict)
    if tool_reports_dict is None:
        tool_reports_dict = load_tool_reports()
    tool_context = format_tool_diagnostics_context(tool_reports_dict)

    prompt = f"""You are a principal software engineer and expert meta-evaluator acting as an objective LLM Judge.
Your objective is to evaluate the QUALITY and ACCURACY of an automated Code Assessment Report generated by "CodeBroker".

You are provided with:
1. THE GROUND TRUTH CODEBASE (the exact files reviewed by CodeBroker).
2. EMPIRICAL STATIC TOOL DIAGNOSTICS (Pylint, Bandit, Radon output reports).
3. THE CODEBROKER ASSESSMENT REPORT (the generated evaluation output).

----------------------------------------
[GROUND TRUTH CODEBASE]
{code_context}
----------------------------------------

----------------------------------------
[GROUND TRUTH STATIC TOOL DIAGNOSTICS (PYLINT / BANDIT / RADON)]
{tool_context}
----------------------------------------

----------------------------------------
[CODEBROKER REPORT UNDER EVALUATION]
{report_text}
----------------------------------------

### Meta-Evaluation Guidelines:
Carefully compare the CodeBroker report against the ground truth codebase and empirical tool diagnostics across these 5 dimensions:

1. **Faithfulness & Grounding (Weight: {weights['faithfulness']})**:
   - Did CodeBroker accurately describe the code's real behavior, classes, and functions?
   - Did it invent features, falsely attribute bugs, or hallucinate non-existent files?
   - Are findings objectively grounded in static analysis diagnostics, including Pylint rules, Bandit security findings, and Radon complexity/maintainability metrics?
   - Score 90-100% if completely grounded; penalize heavily for any hallucination or false bug report.

2. **Completeness & Coverage (Weight: {weights['completeness']})**:
   - Did CodeBroker identify the primary purpose and critical architectural components?
   - Did it evaluate error handling, security (vulnerabilities, injection risks, insecure dependencies scanned via Bandit), efficiency, and automated test presence?
   - Did it evaluate code style, maintainability, and structural complexity (quantified via Radon cyclomatic complexity and Maintainability Index, alongside Pylint)?
   - Did it miss glaring vulnerabilities, critical bugs, or major modules?

3. **Actionability & Specificity (Weight: {weights['actionability']})**:
   - Are the suggested improvements concrete, specific, and actionable for developers?
   - Did it provide clear direction, naming specific functions, files, or patterns (e.g. addressing specific Bandit security warnings, high cyclomatic complexity functions, or Pylint violations)?
   - Penalize generic platitudes (e.g., "write better tests" or "improve readability" without specifics).

4. **Scoring Calibration & Consistency (Weight: {weights['scoring_calibration']})**:
   - Did CodeBroker provide Correctness % and Style % scores?
   - Are the scores calibrated with the actual state of the code, written analysis, and tool outputs:
     * Does the Correctness score reflect Bandit security metrics (vulnerability counts and severity) alongside logical bug risks?
     * Does the Style score align with Radon's Maintainability Index (0-100) and Cyclomatic Complexity alongside Pylint rating?
   - For example, if critical security flaws or high complexity exist, are the scores realistically adjusted?

5. **Structure & Adherence (Weight: {weights['structure_adherence']})**:
   - Does the report follow CodeBroker's standard 4 sections:
     (1) Code Description, (2) Code Correctness Assessment, (3) Code Style Assessment, (4) Suggested Improvements?

Evaluate every dimension objectively and populate the structured schema.
"""
    return prompt


# Unit tests


def test_load_tool_reports_with_files(tmp_path):
    """Tests loading tool reports from a directory containing report files."""
    (tmp_path / "pylint_report.txt").write_text("Rating: 8.5/10", encoding="utf-8")
    (tmp_path / "bandit_report.txt").write_text("No issues identified", encoding="utf-8")
    (tmp_path / "radon_report.txt").write_text("Average complexity: A", encoding="utf-8")
    (tmp_path / "bugsinpy_test_report.txt").write_text("All tests passed", encoding="utf-8")

    reports = load_tool_reports(str(tmp_path))
    assert len(reports) == 4
    assert "pylint_report.txt" in reports
    assert "bandit_report.txt" in reports
    assert "radon_report.txt" in reports
    assert "bugsinpy_test_report.txt" in reports
    assert "8.5/10" in reports["pylint_report.txt"]


def test_load_tool_reports_empty_directory(tmp_path):
    """Tests loading tool reports from an empty directory."""
    reports = load_tool_reports(str(tmp_path))
    assert reports == {}


def test_format_tool_diagnostics_context_empty():
    """Tests fallback notice when no tool reports exist."""
    context = format_tool_diagnostics_context({})
    assert "No pre-generated static tool report files found" in context


def test_format_tool_diagnostics_context_budget_truncation():
    """Tests that very long tool diagnostic reports are truncated within budget."""
    huge_report = "A" * 500
    tool_reports = {"huge_report.txt": huge_report}
    # Set tiny budget
    context = format_tool_diagnostics_context(tool_reports, max_char_budget=100)
    assert "[Truncated" in context


def test_format_codebase_context_budget_truncation():
    """Tests that codebase context adheres to maximum character budget."""
    files = {"file1.py": "x = 1\n" * 100, "file2.py": "y = 2\n" * 100}
    context = format_codebase_context(files, max_char_budget=120)
    assert "Truncated" in context


def test_build_evaluation_prompt_contains_all_dimensions():
    """Tests that the evaluation prompt includes all 5 dimensions and tool grounding."""
    source_files = {"app.py": "def run(): pass\n"}
    report = "# Code Assessment Report\n## 1. Code Description\nClean app"
    weights = {
        "faithfulness": 0.25,
        "completeness": 0.20,
        "actionability": 0.25,
        "scoring_calibration": 0.15,
        "structure_adherence": 0.15,
    }
    tool_reports = {"bandit_report.txt": "No issues"}

    prompt = build_evaluation_prompt(
        source_code_dict=source_files,
        report_text=report,
        weights=weights,
        tool_reports_dict=tool_reports,
    )

    assert "Faithfulness & Grounding" in prompt
    assert "Completeness & Coverage" in prompt
    assert "Actionability & Specificity" in prompt
    assert "Scoring Calibration & Consistency" in prompt
    assert "Structure & Adherence" in prompt
    assert "Bandit" in prompt
    assert "Radon" in prompt
    assert "Pylint" in prompt
    assert "app.py" in prompt
